  file.path(group_output_dir, "ICC_results.csv")
)


# ------------------------------------------------------------
# Bland-Altman analysis
# ------------------------------------------------------------
# Preserve original DWI methodology:
# diff = v1 - v2
# ave = (v1 + v2) / 2
# reldiff = 100 * diff / ave
# Bias and limits of agreement are calculated on reldiff.

bland_altman_dir <- file.path(group_output_dir, "BlandAltman")
dir.create(bland_altman_dir, recursive = TRUE, showWarnings = FALSE)

calculate_bland_altman_summary <- function(pairs, analysis_label) {
  
  pairs %>%
    na.omit() %>%
    group_by(parameter) %>%
    summarise(
      N_pairs = n(),
      Bias = mean(reldiff),
      SD_difference = sd(reldiff),
      Lower_LoA = Bias - 1.96 * SD_difference,
      Upper_LoA = Bias + 1.96 * SD_difference,
      .groups = "drop"
    ) %>%
    filter(N_pairs >= 3) %>%
    mutate(
      Analysis = analysis_label,
      .before = parameter
    ) %>%
    rename(Parameter = parameter)
  
}

create_bland_altman_plot <- function(
    pairs,
    summary_row,
    analysis_label,
    parameter_name,
    group_label
) {
  
  plot_data <- pairs %>%
    filter(parameter == parameter_name) %>%
    na.omit() %>%
    mutate(
      site = factor(
        sprintf("%02d", as.integer(site)),
        levels = c("01", "02", "03", "04")
      )
    )
  
  x_label <- switch(
    parameter_name,
    "T1"    = "Mean T1 (ms)",
    "MOLLI" = "Mean MOLLI T1 (ms)",
    "T2"    = "Mean T2 (ms)",
    "Mean of paired measurements"
  )
  
  n_sites <- length(levels(plot_data$site))
  
  colours <- c(
    "#0057e7",
    "#d62d20",
    "#2ca02c",
    "#800080"
  )[seq_len(n_sites)]
  
  shapes <- c(
    16, # circle
    17, # triangle
    15, # square
    18  # diamond
  )[seq_len(n_sites)]
  
  ggplot(
    plot_data,
    aes(
      x = ave,
      y = reldiff
    )
  ) +
    
    geom_point(
      aes(
        colour = site,
        shape = site
      ),
      size = 3.1,
      alpha = 0.9
    ) +
    
    scale_colour_manual(values = colours) +
    
    scale_shape_manual(values = shapes) +
    
    geom_hline(
      data = summary_row,
      aes(
        yintercept = Bias,
        linetype = "Mean value"
      ),
      linewidth = 0.6
    ) +
    
    geom_hline(
      data = summary_row,
      aes(
        yintercept = Lower_LoA,
        linetype = "Limits of agreement"
      ),
      linewidth = 0.5
    ) +
    
    geom_hline(
      data = summary_row,
      aes(
        yintercept = Upper_LoA,
        linetype = "Limits of agreement"
      ),
      linewidth = 0.5
    ) +
    
    scale_linetype_manual(
      values = c(
        "Mean value" = "solid",
        "Limits of agreement" = "dashed"
      )
    ) +
    
    labs(
      title = paste(
        parameter_name,
        analysis_label,
        "-",
        group_label
      ),
      x = x_label,
      y = "Relative difference (%)",
      colour = "Center",
      shape = "Center",
      linetype = ""
    ) +
    
    theme_bw() +
    
    theme(
      plot.title = element_text(
        hjust = 0.5,
        size = rel(1.5)
      ),
      
      axis.title = element_text(
        size = rel(1.5)
      ),
      
      axis.text = element_text(
        size = rel(1.2)
      ),
      
      legend.title = element_text(
        size = rel(1.3)
      ),
      
      legend.text = element_text(
        size = rel(1.2)
      )
    )
  
}

run_bland_altman <- function(
    dataset,
    visit1,
    visit2,
    analysis_label,
    group_label
) {
  
  pairs <- make_visit_pairs(
    dataset,
    visit1,
    visit2
  ) %>%
    mutate(
      reldiff = 100 * diff / ave
    )
  
  summary <- calculate_bland_altman_summary(
    pairs,
    analysis_label
  )
  
  for (parameter_name in summary$Parameter) {
    
    summary_row <- summary %>%
      filter(
        Parameter == parameter_name
      )
    
    plot <- create_bland_altman_plot(
      pairs = pairs,
      summary_row = summary_row,
      analysis_label = analysis_label,
      parameter_name = parameter_name,
      group_label = group_label
    )
    
    output_file <- file.path(
      bland_altman_dir,
      paste0(
        analysis_label,
        "_",
        parameter_name,
        "_BlandAltman.pdf"
      )
    )
    
    ggsave(
      filename = output_file,
      plot = plot,
      device = "pdf",
      width = 7.5,
      height = 5.5,
      units = "in"
    )
    
  }
  
  summary
  
}

BlandAltman_summary <- purrr::imap_dfr(
  
  analyses,
  
  ~ run_bland_altman(
    dataset = .x$data,
    visit1 = .x$visit1,
    visit2 = .x$visit2,
    analysis_label = str_to_title(.y),
    group_label = group_label
  )
  
)

write_csv(
  BlandAltman_summary,
  file.path(
    bland_altman_dir,
    "BlandAltman_summary.csv"
  )
)

cat("\n==============================\n")
cat("Bland-Altman summary\n")
cat("==============================\n")
print(BlandAltman_summary)

cat("\nAll outputs saved in:", group_output_dir, "\n")
}

