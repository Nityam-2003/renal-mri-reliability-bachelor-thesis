# IMPORTANT: Thesis-specific reliability analysis for quantitative renal MRI.
#
# Run this script from the ``Analysis/BRAINSFit_Registration`` folder after
# ``Analysis.py`` has created the four private BRAINSFit input CSV tables.
# The script analyses healthy volunteers and CKD patients independently and
# writes CoV, ICC, and Bland--Altman outputs only within this folder.
#
# The CoV implementation follows the published de Boer et al. formulation,
# adapted here for the final renal MRI data structure. This script requires the
# R packages tidyverse and irr. Do not commit input tables or generated outputs
# containing study data to a public repository.

library(tidyverse)
library(irr)

# ------------------------------------------------------------
# T1/T2 kidney MRI statistics
# Separate analyses for healthy volunteers and CKD patients:
# CoV + ICC + Bland-Altman
# ------------------------------------------------------------
# Inputs are generated by the Python processing pipeline.
# Each row is one whole-kidney ROI measurement.

script_path <- tryCatch(
  normalizePath(sys.frame(1)$ofile, winslash = "/", mustWork = TRUE),
  error = function(e) NA_character_
)

analysis_dir <- if (!is.na(script_path)) dirname(script_path) else getwd()

# ------------------------------------------------------------
# Read input
# ------------------------------------------------------------

read_input <- function(path) {
  read_csv(path, show_col_types = FALSE) %>%
    mutate(
      ID = as.character(ID),
      site = as.character(site),
      vendor = as.character(vendor),
      visit = as.character(visit),
      anatomy = as.character(anatomy),
      parameter = as.character(parameter),
      value = as.numeric(value)
    ) %>%
    filter(anatomy == "whole")
}

run_group_analysis <- function(
    group_name,
    group_label,
    repeatability_file,
    reproducibility_file
) {
  group_output_dir <- file.path(analysis_dir, group_name)
  dir.create(group_output_dir, recursive = TRUE, showWarnings = FALSE)

  repeatability_data <- read_input(repeatability_file)
  reproducibility_data <- read_input(reproducibility_file)

# ------------------------------------------------------------
# Pair measurements
# ------------------------------------------------------------

make_visit_pairs <- function(dataset, visit1, visit2) {
  
  dataset %>%
    filter(visit %in% c(visit1, visit2)) %>%
    select(ID, site, vendor, visit, parameter, value) %>%
    pivot_wider(
      names_from = visit,
      values_from = value
    ) %>%
    filter(
      !is.na(.data[[visit1]]),
      !is.na(.data[[visit2]])
    ) %>%
    transmute(
      ID,
      site,
      vendor,
      parameter,
      v1 = .data[[visit1]],
      v2 = .data[[visit2]],
      diff = v1 - v2,
      ave = (v1 + v2) / 2,
      ratio = diff^2 / ave^2
    )
  
}

# ------------------------------------------------------------
# CoV
# ------------------------------------------------------------

calculate_cov <- function(df, grouping_vars) {
  
  df %>%
    na.omit() %>%
    group_by(across(all_of(grouping_vars))) %>%
    summarise(
      N = n(),
      CV = 100 * sqrt(1 / (2 * N) * sum(ratio)),
      .groups = "drop"
    ) %>%
    filter(N >= 3)
  
}

cov_site <- function(df) {
  calculate_cov(df, c("parameter", "site"))
}

cov_vendor <- function(df) {
  calculate_cov(df, c("parameter", "vendor"))
}

cov_total <- function(df) {
  calculate_cov(df, "parameter") %>%
    mutate(group = "Total")
}

run_cov <- function(dataset, visit1, visit2) {
  
  pairs <- make_visit_pairs(dataset, visit1, visit2)
  
  list(
    pairs = pairs,
    site = cov_site(pairs),
    vendor = cov_vendor(pairs),
    total = cov_total(pairs)
  )
  
}

# ------------------------------------------------------------
# Analyses
# ------------------------------------------------------------

analyses <- list(
  
  repeatability = list(
    data = repeatability_data,
