# ------------------------------------------------------------
# ICC analysis
# ------------------------------------------------------------
# Preserve original DWI methodology:
# ICC(2,1), two-way random effects, absolute agreement, single measurement.

calculate_icc_one_group <- function(df) {
  df_ICC <- df %>%
    select(v1, v2) %>%
    na.omit()
  
  if (nrow(df_ICC) < 3) {
    return(tibble(
      N_pairs = nrow(df_ICC),
      ICC = NA_real_,
      Lower_CI = NA_real_,
      Upper_CI = NA_real_,
      F_value = NA_real_,
      P_value = NA_real_
    ))
  }
  
  icc_res <- tryCatch(
    icc(
      df_ICC[, c("v1", "v2")],
      model = "twoway",
      type = "agreement",
      unit = "single"
    ),
    error = function(e) NULL
  )
  
  if (is.null(icc_res)) {
    return(tibble(
      N_pairs = nrow(df_ICC),
      ICC = NA_real_,
      Lower_CI = NA_real_,
      Upper_CI = NA_real_,
      F_value = NA_real_,
      P_value = NA_real_
    ))
  }
  
  tibble(
    N_pairs = nrow(df_ICC),
    ICC = icc_res$value,
    Lower_CI = icc_res$lbound,
    Upper_CI = icc_res$ubound,
    F_value = icc_res$Fvalue,
    P_value = icc_res$p.value
  )
}

calculate_icc_grouped <- function(pairs, grouping_vars, grouping_label, group_column = NULL) {
  pairs %>%
    group_by(across(all_of(grouping_vars))) %>%
    group_modify(~ calculate_icc_one_group(.x)) %>%
    ungroup() %>%
    filter(N_pairs >= 3) %>%
    mutate(
      Level = grouping_label,
      Group = if (is.null(group_column)) "Total" else as.character(.data[[group_column]]),
      Parameter = parameter
    ) %>%
    select(
      Level,
      Group,
      Parameter,
      N_pairs,
      ICC,
      Lower_CI,
      Upper_CI,
      F_value,
      P_value
    )
}

run_icc <- function(dataset, visit1, visit2, analysis_label) {
  pairs <- make_visit_pairs(dataset, visit1, visit2)
  
  bind_rows(
    calculate_icc_grouped(
      pairs,
      c("parameter", "site"),
      grouping_label = "Center",
      group_column = "site"
    ),
    calculate_icc_grouped(
      pairs,
      c("parameter", "vendor"),
      grouping_label = "Vendor",
      group_column = "vendor"
    ),
    calculate_icc_grouped(
      pairs,
      c("parameter"),
      grouping_label = "Overall"
    )
  ) %>%
    mutate(Analysis = analysis_label, .before = Level)
}

ICC_results <- purrr::imap_dfr(
  analyses,
  ~ run_icc(
    dataset = .x$data,
    visit1 = .x$visit1,
    visit2 = .x$visit2,
    analysis_label = str_to_title(.y)
  )
)

print("ICC results")
print(ICC_results)

write_csv(
